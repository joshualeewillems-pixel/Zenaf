/**
 * Assisted chunk mode: preprocess transcript and split into a handful of chunks
 * for reliable extraction of very long meetings. No AI; heuristic boundaries
 * at paragraph breaks, speaker changes, and topic/title lines.
 *
 * Default: 3–6 chunks, ~4k–8k chars each (legacy “large chunk” assist).
 * Interactive fast: smaller user-facing chunks; tail is never allowed to balloon past
 * max size (the legacy loop used to dump the entire remainder into the last chunk).
 */

import type { ManualProcessingChunk } from './types'

const nanoid = () => `chunk-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 9)}`

/** Safe size range per chunk (chars) — default assisted mode. */
const MIN_CHUNK_CHARS = 4000
const MAX_CHUNK_CHARS = 8000

/** Target number of chunks for long transcripts — default. */
const TARGET_CHUNKS_MIN = 3
const TARGET_CHUNKS_MAX = 6

/** Interactive / fast_local–aligned manual chunks (Vision Execution extract). */
const FAST_MIN_CHUNK_CHARS = 2200
const FAST_MAX_CHUNK_CHARS = 3800
const FAST_TARGET_CHUNKS_MIN = 4
const FAST_TARGET_CHUNKS_MAX = 10

export type BuildManualChunksOptions = {
  /** Use smaller chunks and allow more of them (matches interactive extract-meeting fast_local). */
  interactiveFast?: boolean
}

/**
 * Pre-clean transcript before extraction (Layer 1 view).
 * Normalize speaker labels, preserve proper names, remove obvious ASR garbage,
 * avoid over-cleaning hesitation/repetition that may carry signal meaning.
 */
export function preprocessTranscript(raw: string): string {
  let text = (raw ?? '').trim()
  if (!text) return ''

  const lines = text.split(/\r?\n/)
  const out: string[] = []
  let skippedHeader = false

  const asrGarbage = /^\[?(inaudible|crosstalk|laughter|applause|silence|background noise)\]?\s*$/i
  const speakerStart = /^(speaker\s*[a-z0-9]+|SPEAKER\s*\d+)\s*[:\-]\s*/i

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i] ?? ''
    let trimmed = line.trim()

    // Skip leading export/metadata blocks (once)
    if (!skippedHeader) {
      if (
        /^(Exported from|Transcript (export|generated)|Generated by|Powered by|—+\s*$)/i.test(trimmed) ||
        /^\[?\d{1,2}:\d{2}(:\d{2})?(\s*[AP]M)?\]?\s*$/i.test(trimmed) ||
        /^https?:\/\//i.test(trimmed)
      ) {
        continue
      }
      if (trimmed === '' && out.length === 0) continue
      skippedHeader = true
    }

    // Remove obvious ASR garbage lines only (do not strip hesitation from content)
    if (asrGarbage.test(trimmed)) continue

    // Normalize speaker labels for consistency (Speaker 1:, Speaker 2:, …)
    const speakerMatch = trimmed.match(speakerStart)
    if (speakerMatch) {
      const label = speakerMatch[1]
      const rest = trimmed.slice(speakerMatch[0].length).trim()
      const num = label.replace(/^(speaker|SPEAKER)\s*/i, '').trim()
      const normalized = `Speaker ${num}:${rest ? ' ' + rest : ''}`
      out.push(normalized)
      continue
    }

    // Collapse repeated separator-only lines to one blank
    if (/^[-–—_\s*=]{2,}$/.test(trimmed)) {
      if (out.length > 0 && (out[out.length - 1] ?? '') !== '') {
        out.push('')
      }
      continue
    }

    out.push(line)
  }

  // Trim trailing blanks and rejoin
  while (out.length > 0 && (out[out.length - 1] ?? '').trim() === '') {
    out.pop()
  }
  return out.join('\n').trim()
}

/**
 * Best-effort title from first line or first sentence (trimmed, capped).
 */
function firstLineOrSentence(text: string, maxLen = 80): string {
  const t = text.trim()
  if (!t) return 'Chunk'
  const firstLine = t.split(/\r?\n/)[0]?.trim() ?? ''
  const firstSentence = firstLine.split(/[.!?]\s+/)[0]?.trim() ?? firstLine
  const candidate = firstSentence || firstLine
  return candidate.length > maxLen ? candidate.slice(0, maxLen) + '…' : candidate
}

/**
 * Find candidate split positions: start index of each "block" (paragraph or speaker/title line).
 * Returns indices into text where a new block starts (including 0).
 */
function findBlockStarts(text: string): number[] {
  const starts: number[] = [0]
  const lines = text.split(/\r?\n/)
  let offset = 0
  const speakerOrTitle = /^([A-Za-z][A-Za-z0-9_\s\-\.]{0,60})\s*[\:\-]\s*|^#{1,3}\s+.+|^(\*+\s*)?(Agenda|Topic|Section|Part)\s*[\d:\.\-]/i

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i] ?? ''
    const lineEnd = offset + line.length + (i < lines.length - 1 ? 1 : 0) // +1 for newline
    const trimmed = line.trim()

    // Paragraph break (blank line): next block starts after this line
    if (trimmed === '') {
      if (lineEnd < text.length && (starts.length === 0 || starts[starts.length - 1] !== lineEnd)) {
        starts.push(lineEnd)
      }
      offset = lineEnd
      continue
    }

    // Speaker change or topic/title line (strong boundary)
    if (speakerOrTitle.test(trimmed)) {
      if (offset > 0 && !starts.includes(offset)) {
        starts.push(offset)
      }
    }

    offset = lineEnd
  }

  return [...new Set(starts)].sort((a, b) => a - b)
}

/**
 * The main chunk loop sets the last chunk to run to `len`, which can exceed `maxC` and
 * force many internal evidence segments + long LLM tails. Split only an oversized tail.
 */
function splitOversizedInteractiveTail(
  chunks: ManualProcessingChunk[],
  fullText: string,
  maxC: number,
  blockStarts: number[],
): ManualProcessingChunk[] {
  if (chunks.length === 0) return chunks
  const lastIdx = chunks.length - 1
  const last = chunks[lastIdx]!
  if (last.text.length <= maxC) return chunks

  const absStart = last.startOffset
  const absEnd = last.endOffset
  const pieces: ManualProcessingChunk[] = []
  let s = absStart
  while (s < absEnd) {
    const hardCap = Math.min(absEnd, s + maxC)
    const candidates = blockStarts.filter((b) => b > s && b <= hardCap)
    let chunkEnd = candidates.length > 0 ? candidates[candidates.length - 1]! : hardCap
    if (chunkEnd <= s) chunkEnd = hardCap
    const slice = fullText.slice(s, chunkEnd).trim()
    if (slice.length > 0) {
      pieces.push({
        id: nanoid(),
        title: firstLineOrSentence(slice),
        text: slice,
        startOffset: s,
        endOffset: chunkEnd,
      })
    }
    if (chunkEnd <= s) break
    s = chunkEnd
  }
  if (pieces.length === 0) return chunks
  return [...chunks.slice(0, lastIdx), ...pieces]
}

/**
 * Long **external** extract-meeting: one HTTP call per chunk; keep each `notes` body
 * within the same character budget as a single external call (e.g. 92k chars in
 * `extractConstants.ts`). Splits on speaker/paragraph
 * boundaries where possible; otherwise newline or hard cap. Uses trimmed raw notes
 * (same substrate as the single-call external path).
 */
export function buildExternalBudgetChunks(notes: string, maxCharsPerChunk: number): ManualProcessingChunk[] {
  const text = (notes ?? '').trim()
  if (!text) return []
  const maxC = Math.max(1000, Math.floor(maxCharsPerChunk))
  const len = text.length
  if (len <= maxC) {
    return [
      {
        id: nanoid(),
        title: firstLineOrSentence(text),
        text,
        startOffset: 0,
        endOffset: len,
      },
    ]
  }

  const blockStarts = findBlockStarts(text)
  const chunks: ManualProcessingChunk[] = []
  let start = 0

  while (start < len) {
    const hardEnd = Math.min(start + maxC, len)
    if (hardEnd >= len) {
      const slice = text.slice(start, len).trim()
      if (slice.length > 0) {
        chunks.push({
          id: nanoid(),
          title: firstLineOrSentence(slice),
          text: slice,
          startOffset: start,
          endOffset: len,
        })
      }
      break
    }

    const candidates = blockStarts.filter((b) => b > start && b <= hardEnd)
    let chunkEnd = candidates.length > 0 ? candidates[candidates.length - 1]! : hardEnd
    if (chunkEnd <= start) {
      const window = text.slice(start, hardEnd)
      const lastNl = window.lastIndexOf('\n')
      chunkEnd = lastNl > 0 ? start + lastNl + 1 : hardEnd
    }
    if (chunkEnd <= start) chunkEnd = hardEnd

    const slice = text.slice(start, chunkEnd).trim()
    if (slice.length > 0) {
      chunks.push({
        id: nanoid(),
        title: firstLineOrSentence(slice),
        text: slice,
        startOffset: start,
        endOffset: chunkEnd,
      })
    }
    start = chunkEnd
    if (start >= len) break
    if (slice.length === 0) start = hardEnd
  }

  if (chunks.length === 0) {
    return [
      {
        id: nanoid(),
        title: firstLineOrSentence(text),
        text,
        startOffset: 0,
        endOffset: len,
      },
    ]
  }

  return chunks
}

/**
 * Build manual processing chunks from preprocessed transcript. Prefers boundaries at
 * paragraph breaks, speaker changes, and major topic/title lines.
 */
export function buildManualProcessingChunks(
  notes: string,
  options?: BuildManualChunksOptions,
): ManualProcessingChunk[] {
  const fast = Boolean(options?.interactiveFast)
  const minC = fast ? FAST_MIN_CHUNK_CHARS : MIN_CHUNK_CHARS
  const maxC = fast ? FAST_MAX_CHUNK_CHARS : MAX_CHUNK_CHARS
  const tMin = fast ? FAST_TARGET_CHUNKS_MIN : TARGET_CHUNKS_MIN
  const tMax = fast ? FAST_TARGET_CHUNKS_MAX : TARGET_CHUNKS_MAX

  const text = preprocessTranscript(notes)
  if (!text) return []

  const len = text.length
  if (len <= maxC) {
    return [
      {
        id: nanoid(),
        title: firstLineOrSentence(text),
        text,
        startOffset: 0,
        endOffset: len,
      },
    ]
  }

  const blockStarts = findBlockStarts(text)
  const targetChunkSize = Math.max(minC, Math.min(maxC, Math.ceil(len / 4)))
  const numChunks = Math.max(tMin, Math.min(tMax, Math.ceil(len / targetChunkSize)))
  const idealSize = Math.ceil(len / numChunks)

  let chunks: ManualProcessingChunk[] = []
  let chunkStart = 0

  for (let c = 0; c < numChunks; c++) {
    const isLast = c === numChunks - 1
    const maxEnd = isLast ? len : Math.min(len, chunkStart + maxC)
    let chunkEnd: number

    if (isLast) {
      chunkEnd = len
    } else {
      const targetEnd = Math.min(maxEnd, chunkStart + idealSize)
      const candidates = blockStarts.filter((s) => s > chunkStart && s <= maxEnd)
      const atOrPastTarget = candidates.filter((s) => s >= targetEnd - 500)
      const beforeTarget = candidates.filter((s) => s < targetEnd - 500)
      const pick = atOrPastTarget[0] ?? beforeTarget[beforeTarget.length - 1] ?? Math.min(chunkStart + targetChunkSize, maxEnd)
      chunkEnd = pick <= chunkStart ? Math.min(chunkStart + targetChunkSize, maxEnd) : pick
    }

    const chunkText = text.slice(chunkStart, chunkEnd).trim()
    if (chunkText) {
      chunks.push({
        id: nanoid(),
        title: firstLineOrSentence(chunkText),
        text: chunkText,
        startOffset: chunkStart,
        endOffset: chunkEnd,
      })
    }
    chunkStart = chunkEnd
  }

  if (fast && chunks.length > 0) {
    chunks = splitOversizedInteractiveTail(chunks, text, maxC, blockStarts)
  }

  if (chunks.length === 0) {
    chunks.push({
      id: nanoid(),
      title: firstLineOrSentence(text),
      text,
      startOffset: 0,
      endOffset: len,
    })
  }

  return chunks
}
