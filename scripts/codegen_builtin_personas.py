#!/usr/bin/env python3
"""Codegen: backend persona definitions -> frontend TypeScript.

Single source of truth: `local_ai/zenaf_tools.py::BUILT_IN_PERSONA_DEFINITIONS`.
This script generates `frontend/src/perspectives/builtinPersonas.generated.ts`,
which the frontend composes with its presentation metadata (icons, actor
lanes) instead of carrying a hand-maintained copy of the persona content.

The old drift (conversation claimed a frontend/backend sync the code never
got) is structurally impossible now: the generated file is never hand-edited,
`npm run prebuild` regenerates it on every frontend build, and
`tests/test_builtin_personas_codegen.py` fails if the checked-in copy is
stale.

Usage:
    python3 scripts/codegen_builtin_personas.py            # regenerate in place
    python3 scripts/codegen_builtin_personas.py --check    # exit 1 if stale
    python3 scripts/codegen_builtin_personas.py --out PATH # write elsewhere
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
GENERATED_PATH = REPO_ROOT / "frontend" / "src" / "perspectives" / "builtinPersonas.generated.ts"

sys.path.insert(0, str(REPO_ROOT))

# Content fields the frontend's PerspectiveAgent carries that are authored
# on the backend. Presentation-only fields (icon, avatar, actor_kind,
# createdAt) stay in the frontend's BUILTIN_PRESENTATION map.
CONTENT_FIELDS = (
    "id",
    "name",
    "strand",
    "role",
    "purpose",
    "values",
    "aversions",
    "reasoningStyle",
    "tone",
    "domain",
    "decisionRule",
    "worldview",
    "constraints",
    "examplePhrases",
    "tasteCompass",
)


def _ts_string(value: str) -> str:
    # JSON string syntax is valid TypeScript for strings.
    return json.dumps(value, ensure_ascii=False)


def _ts_value(value) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def generate() -> str:
    from local_ai.zenaf_tools import BUILT_IN_PERSONA_DEFINITIONS

    keys = sorted(BUILT_IN_PERSONA_DEFINITIONS.keys())
    entries: list[str] = []
    for key in keys:
        defn = BUILT_IN_PERSONA_DEFINITIONS[key]
        fields: list[str] = []
        for fname in CONTENT_FIELDS:
            if fname not in defn or defn[fname] is None:
                continue
            val = defn[fname]
            if isinstance(val, str) and not val.strip():
                continue
            if isinstance(val, list) and not val:
                continue
            fields.append(f"    {fname}: {_ts_value(val)},")
        entries.append("  %s: {\n%s\n  }," % (_ts_string(key), "\n".join(fields)))

    return """/**
 * DO NOT EDIT — generated by scripts/codegen_builtin_personas.py
 * from local_ai/zenaf_tools.py :: BUILT_IN_PERSONA_DEFINITIONS.
 *
 * The backend is the single source of truth for persona content. The
 * frontend composes this with presentation metadata (icons, actor lanes)
 * in perspectives/types.ts. Regenerate with `npm run prebuild`.
 */

export type BuiltinPersonaTasteCompass = {
  summary: string
  shaped_by_user: boolean
}

export type GeneratedBuiltinPersonaContent = {
  id: string
  name: string
  strand?: 'word' | 'number' | 'image' | 'sound' | 'body' | 'people' | 'self'
  role: string
  purpose: string
  values: string[]
  aversions: string[]
  reasoningStyle: string[]
  tone: string
  domain: string[]
  decisionRule: string
  worldview?: string
  constraints?: string[]
  examplePhrases?: string[]
  tasteCompass?: BuiltinPersonaTasteCompass | string
}

export const GENERATED_BUILTIN_PERSONA_IDS: string[] = [
%s
]

export const GENERATED_BUILTIN_PERSONA_CONTENT: Record<string, GeneratedBuiltinPersonaContent> = {
%s
}
""" % (
        "\n".join(f"  {_ts_string(k)}," for k in keys),
        "\n".join(entries),
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the checked-in file is stale")
    ap.add_argument("--out", default=str(GENERATED_PATH), help="output path")
    args = ap.parse_args()

    text = generate()
    out = Path(args.out)
    if args.check:
        with tempfile.NamedTemporaryFile("w", suffix=".ts", delete=False) as tmp:
            tmp.write(text)
            tmp_path = tmp.name
        current = out.read_text() if out.exists() else ""
        fresh = Path(tmp_path).read_text()
        if current != fresh:
            print(
                "STALE: frontend/src/perspectives/builtinPersonas.generated.ts is out of date.\n"
                "Run: python3 scripts/codegen_builtin_personas.py",
                file=sys.stderr,
            )
            return 1
        print("generated personas are in sync")
        return 0

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
